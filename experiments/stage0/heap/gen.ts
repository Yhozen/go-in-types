// Generates one heap micro benchmark as a .ts file (run by tsrs, measured with
// --extendedDiagnostics). See README.md.
//
//   node gen.ts <node> <obj> <bind> <op> <N> <K> > out.ts
//
// node: tuple | iface        trie node (and heap box) representation
// obj:  t16 | t8 | lua | i16 | i8   object representation
//       (lua: an 8-tuple holding a 16-slot tuple, like lua-in-types tables)
// bind: arg | infer | inferc | tuple   how the loop passes the heap on
// op:   none | read | write | alloc
// N:    live objects besides the 256-object working set (multiple of 256)
// K:    loop steps

export type Cfg = {
  node: "tuple" | "iface";
  obj: "t16" | "t8" | "lua" | "i16" | "i8";
  bind: "arg" | "infer" | "inferc" | "tuple";
  op: "none" | "read" | "write" | "alloc";
  n: number;
  k: number;
  /** objects carry a deferred tuple reference with an outer type parameter (`[Id, E0]` in `Obj<Id>`) in field 2 */
  dfr?: boolean;
  /** objects carry a value copied from a source-written object literal (`ImgV["k"]`) in field 2: generic-looking */
  glit?: boolean;
  /** empty trie nodes written as tuple literals of an alias (deferred, like trie.ts E1..E6) */
  elit?: boolean;
  /** long run (op write, bind arg): this many chained statements of K writes each, distinct values per round */
  rounds?: number;
};

const HEX = "0123456789abcdef".split("");
const hex = (v: number, w: number) => v.toString(16).padStart(w, "0");
const range = (n: number) => Array.from({ length: n }, (_, i) => i);

export function generate(c: Cfg): string {
  const out: string[] = [];
  const w = (s: string) => out.push(s);
  w(`// GENERATED by experiments/stage0/heap/gen.ts ${JSON.stringify(c)}`);
  w(`export {};`);
  w(`interface Ix { ${HEX.map((d, i) => `"${d}": "${i}";`).join(" ")} }`);

  // ---- trie nodes
  const A16 = range(16).map((i) => `A${i}`);
  if (c.node === "tuple") {
    w(`type Mk16<${A16.join(", ")}> = A0 extends unknown ? [${A16.join(", ")}] : never;`);
    w(`type Ch<N, D> = N[Ix[D & keyof Ix] & keyof N];`);
    w(`type HeapMk<Nx, R> = Nx extends unknown ? [Nx, R] : never;`);
    w(`type RootOf<H> = H["1" & keyof H];`);
    w(`type NextOf<H> = H["0" & keyof H];`);
    w(`type HeapC = [string, unknown];`);
  } else {
    w(`interface N16<${A16.join(", ")}> { ${HEX.map((d, i) => `"${d}": A${i};`).join(" ")} }`);
    w(`type Mk16<${A16.join(", ")}> = N16<${A16.join(", ")}>;`);
    w(`type Ch<N, D> = N[D & keyof N];`);
    w(`interface HP<Nx, R> { n: Nx; r: R }`);
    w(`type HeapMk<Nx, R> = HP<Nx, R>;`);
    w(`type RootOf<H> = H["r" & keyof H];`);
    w(`type NextOf<H> = H["n" & keyof H];`);
    w(`type HeapC = HP<string, unknown>;`);
  }
  // SetC<N, D, V>: node N with child D replaced by V
  const childKey = (i: number) => (c.node === "tuple" ? `"${i}"` : `"${HEX[i]}"`);
  const rebuild = (i: number) =>
    `Mk16<${range(16)
      .map((j) => (j === i ? "V" : `N[${childKey(j)} & keyof N]`))
      .join(", ")}>`;
  w(
    `type SetC<N, D, V> = ${HEX.map((d, i) => `D extends "${d}" ? ${rebuild(i)} :`).join(" ")} never;`,
  );
  w(`type E0 = undefined;`);
  w(`interface ImgV { k: { a: "x" } }`);
  w(`type EA = [${range(16).map(() => "E0").join(", ")}];`);
  if (c.elit && c.node === "tuple") {
    w(`type E1 = [${range(16).map(() => "E0").join(", ")}];`);
    for (let d = 2; d <= 4; d++) w(`type E${d} = [${range(16).map(() => `E${d - 1}`).join(", ")}];`);
  } else {
    w(`type E1 = Mk16<${range(16).map(() => "undefined").join(", ")}>;`);
    for (let d = 2; d <= 4; d++) w(`type E${d} = Mk16<${range(16).map(() => `E${d - 1}`).join(", ")}>;`);
  }

  // ---- objects
  const F = c.obj === "t8" || c.obj === "i8" ? 8 : 16;
  const fF = range(F).map((i) => `F${i}`);
  if (c.obj === "t16" || c.obj === "t8") {
    w(`type OMk<${fF.join(", ")}> = F0 extends unknown ? [${fF.join(", ")}] : never;`);
    w(`type Fld<O, I> = O[Ix[I & keyof Ix] & keyof O];`);
    const reb = (i: number) =>
      `OMk<${range(F)
        .map((j) => (j === i ? "V" : `O["${j}" & keyof O]`))
        .join(", ")}>`;
    w(`type SetF<O, I, V> = ${range(F).map((i) => `I extends "${HEX[i]}" ? ${reb(i)} :`).join(" ")} never;`);
  } else if (c.obj === "i16" || c.obj === "i8") {
    w(`interface OI<${fF.join(", ")}> { ${range(F).map((i) => `"${HEX[i]}": F${i};`).join(" ")} }`);
    w(`type OMk<${fF.join(", ")}> = OI<${fF.join(", ")}>;`);
    w(`type Fld<O, I> = O[I & keyof O];`);
    const reb = (i: number) =>
      `OMk<${range(F)
        .map((j) => (j === i ? "V" : `O["${HEX[j]}" & keyof O]`))
        .join(", ")}>`;
    w(`type SetF<O, I, V> = ${range(F).map((i) => `I extends "${HEX[i]}" ? ${reb(i)} :`).join(" ")} never;`);
  } else {
    // lua: [id, arr, tag, x, ad, count, slots(16), meta]; field "0" is the id, others in slots
    w(`type Sl<${fF.join(", ")}> = F0 extends unknown ? [${fF.join(", ")}] : never;`);
    w(`type Tb<Id, S> = Id extends unknown ? [Id, "a", "s", "x", "0", "16", S, undefined] : never;`);
    w(`type OMk<${fF.join(", ")}> = Tb<F0, Sl<${fF.join(", ")}>>;`);
    w(`type SlotsOf<O> = O["6" & keyof O];`);
    w(`type Fld<O, I> = I extends "0" ? O["0" & keyof O] : SlotsOf<O>[Ix[I & keyof Ix] & keyof SlotsOf<O>];`);
    const reb = (i: number) =>
      `Tb<O["0" & keyof O], Sl<${range(F)
        .map((j) => (j === i ? "V" : `S["${j}" & keyof S]`))
        .join(", ")}>>`;
    w(`type SetF<O, I, V> = SetFS<O, SlotsOf<O>, I, V>;`);
    w(`type SetFS<O, S, I, V> = ${range(F).map((i) => `I extends "${HEX[i]}" ? ${reb(i)} :`).join(" ")} never;`);
  }
  // a fresh object with id Id in field 0
  w(`type Obj<Id> = OMk<Id, ${range(F - 1).map((i) => (c.glit && i === 1 ? `ImgV["k"]` : c.dfr && i === 1 ? "[Id, E0]" : `"v"`)).join(", ")}>;`);

  // ---- heap ops
  w(
    "type Get<H, Id> = Id extends `${infer A}${infer B}${infer C}${infer D}${infer E}` ? Ch<Ch<Ch<Ch<Ch<RootOf<H>, A>, B>, C>, D>, E> : never;",
  );
  w(
    "type Put<R, Id, V> = Id extends `${infer A}${infer B}${infer C}${infer D}${infer E}` ? PutI<R, A, B, C, D, E, Ch<R, A>, V> : never;",
  );
  w(`type PutI<R, A, B, C, D, E, R1, V> = PutJ<R, A, R1, B, C, D, E, Ch<R1, B>, V>;`);
  w(`type PutJ<R, A, R1, B, C, D, E, R2, V> = PutK<R, A, R1, B, R2, C, D, E, Ch<R2, C>, V>;`);
  w(
    `type PutK<R, A, R1, B, R2, C, D, E, R3, V> = SetC<R, A, SetC<R1, B, SetC<R2, C, SetC<R3, D, SetC<Ch<R3, D>, E, V>>>>>;`,
  );
  w(`type Store<H, Id, O> = HeapMk<NextOf<H>, Put<RootOf<H>, Id, O>>;`);
  w(`type Write<H, Id, F, V> = Store<H, Id, SetF<Get<H, Id>, F, V>>;`);
  w(`type Read<H, Id, F> = Fld<Get<H, Id>, F>;`);
  w(`type Alloc<H, O> = HeapMk<At<IncT, NextOf<H>>, Put<RootOf<H>, NextOf<H>, O>>;`);

  // ---- the heap: working set (block 000) + n/256 blocks
  w(`type Full1<Q extends string> = Mk16<${HEX.map((d) => `Obj<\`\${Q}${d}\`>`).join(", ")}>;`);
  w(`type Full2<P extends string> = Mk16<${HEX.map((d) => `Full1<\`\${P}${d}\`>`).join(", ")}>;`);
  const blocks = 1 + c.n / 256;
  if (!Number.isInteger(blocks) || blocks > 4095) throw new Error("bad n");
  for (let b = 0; b < blocks; b++) w(`type B_${hex(b, 3)} = Full2<"${hex(b, 3)}">;`);
  const has = (p: string) => {
    // any block with prefix p (hex digits of the 3-digit block number)?
    const lo = parseInt(p.padEnd(3, "0"), 16);
    return lo < blocks;
  };
  // level nodes: prefix of 2 digits -> children blocks (depth 2 nodes) ; empty = E2
  for (let a = 0; a < 16; a++)
    for (let b = 0; b < 16; b++) {
      const p = HEX[a] + HEX[b];
      if (!has(p)) continue;
      w(`type L_${p} = Mk16<${HEX.map((d) => (has(p + d) ? `B_${p}${d}` : "E2")).join(", ")}>;`);
    }
  for (let a = 0; a < 16; a++) {
    const p = HEX[a];
    if (!has(p)) continue;
    w(`type L_${p} = Mk16<${HEX.map((d) => (has(p + d) ? `L_${p}${d}` : "E3")).join(", ")}>;`);
  }
  w(`type Root = Mk16<${HEX.map((d) => (has(d) ? `L_${d}` : "E4")).join(", ")}>;`);
  const allocBase = blocks * 256;
  w(`type H0 = HeapMk<"${hex(allocBase, 5)}", Root>;`);

  // ---- loop tables
  const K = c.k;
  const tok = (i: number) => (i >= K ? "end" : `s${i}`);
  const tgt = (i: number) => hex((i * 97 + 13) % 256, 5);
  w(`interface Seq { ${range(K).map((i) => `${tok(i)}: "${tok(i + 1)}";`).join(" ")} }`);
  w(`interface Tgt { ${range(K).map((i) => `${tok(i)}: "${tgt(i)}";`).join(" ")} }`);
  w(`interface Val { ${range(K).map((i) => `${tok(i)}: "w${i}";`).join(" ")} }`);
  w(`interface IncT { ${range(K + 1).map((i) => `"${hex(allocBase + i, 5)}": "${hex(allocBase + i + 1, 5)}";`).join(" ")} }`);
  const T = `At<Tgt, I>`;
  const opH = {
    none: `H`,
    read: `H`,
    write: `Write<H, ${T}, "1", At<Val, I>>`,
    alloc: `Alloc<H, Obj<I>>`,
  }[c.op];
  const opA = c.op === "read" ? `Read<H, ${T}, "0">` : `A`;
  const nx = `At<Seq, I>`;
  // loop tables are read by a conditional: `I & keyof T` on a K-key interface adds ~K relation entries per step
  w(`type At<T, I> = I extends keyof T ? T[I] : never;`);
  if (c.rounds) {
    w(`type LoopR<H, I, Rd extends string> = I extends "end" ? [H] : LoopR<Write<H, ${T}, "1", \`\${Rd}\${At<Val, I> & string}\`>, ${nx}, Rd>;`);
    for (let r = 1; r <= c.rounds; r++) w(`type Res_${r} = LoopR<${r === 1 ? "H0" : `Res_${r - 1}[0]`}, "s0", "r${r}">;`);
    w(`type Res = Res_${c.rounds};`);
  } else if (c.bind === "arg") {
    w(`type Loop<H, I, A> = I extends "end" ? [H, A] : Loop<${opH}, ${nx}, ${opA}>;`);
    w(`type Res = Loop<H0, "s0", "x">;`);
  } else if (c.bind === "infer" || c.bind === "inferc") {
    const ext = c.bind === "inferc" ? " extends HeapC" : "";
    w(
      `type Loop<H, I, A> = I extends "end" ? [H, A] : ${opH} extends infer H2${ext} ? Loop<H2, ${nx}, ${opA}> : never;`,
    );
    w(`type Res = Loop<H0, "s0", "x">;`);
  } else {
    w(
      `type Loop<S> = S extends [infer H, infer I, infer A] ? I extends "end" ? [H, A] : Loop<[${opH}, ${nx}, ${opA}]> : never;`,
    );
    w(`type Res = Loop<[H0, "s0", "x"]>;`);
  }
  // correctness check (errors if wrong)
  const last = K - 1;
  let chk: string, expect: string;
  if (c.op === "read") {
    chk = `Res[1]`;
    expect = `"${tgt(last)}"`;
  } else if (c.op === "write") {
    chk = `Read<Res[0], "${tgt(last)}", "1">`;
    expect = c.rounds ? `"r${c.rounds}w${last}"` : `"w${last}"`;
  } else if (c.op === "alloc") {
    chk = `Read<Res[0], "${hex(allocBase + last, 5)}", "0">`;
    expect = `"s${last}"`;
  } else {
    chk = `Read<Res[0], "${hex(255, 5)}", "0">`;
    expect = `"000ff"`;
  }
  w(`type Chk = ${chk};`);
  w(`declare const chk: Chk;`);
  w(`export const ok: ${expect} = chk;`);
  // \`any\` passes the check above: assert the result is not any (nor never)
  w(`type IsAnyOrNever<T> = [T] extends [never] ? true : 0 extends 1 & T ? true : false;`);
  w(`export const notAny: false = null! as IsAnyOrNever<Chk>;`);
  return out.join("\n") + "\n";
}

if (import.meta.main) {
  const [node, obj, bind, op, n, k] = process.argv.slice(2);
  process.stdout.write(
    generate({ node, obj, bind, op, n: Number(n), k: Number(k) } as Cfg),
  );
}
