// Package softfloat is the soft-float library the go-in-types front end
// lowers every float operation to (docs/DESIGN.md, "Lowering"). A float
// value is its IEEE 754 bit pattern: uint64 for float64, uint32 for
// float32. softfloat64.go is Go's runtime/softfloat64.go; this file is the
// exported API the front end calls by name (frontend/lower.go). The front
// end injects both files as GOROOT/src/gointypes/softfloat via the overlay.
package softfloat

import (
	"math"
	"strconv"
)

// float64 arithmetic.

func Add64(x, y uint64) uint64 { return fadd64(x, y) }
func Sub64(x, y uint64) uint64 { return fsub64(x, y) }
func Mul64(x, y uint64) uint64 { return fmul64(x, y) }
func Div64(x, y uint64) uint64 { return fdiv64(x, y) }
func Neg64(x uint64) uint64    { return fneg64(x) }

// float64 comparisons (false if either operand is NaN, except Ne64).

func Eq64(x, y uint64) bool { return feq64(x, y) }
func Ne64(x, y uint64) bool { return !feq64(x, y) }
func Lt64(x, y uint64) bool { return fgt64(y, x) }
func Le64(x, y uint64) bool { return fge64(y, x) }
func Gt64(x, y uint64) bool { return fgt64(x, y) }
func Ge64(x, y uint64) bool { return fge64(x, y) }

// float32 arithmetic (through float64, as the runtime does).

func Add32(x, y uint32) uint32 { return fadd32(x, y) }
func Sub32(x, y uint32) uint32 { return fadd32(x, y^(1<<31)) }
func Mul32(x, y uint32) uint32 { return fmul32(x, y) }
func Div32(x, y uint32) uint32 { return fdiv32(x, y) }
func Neg32(x uint32) uint32    { return x ^ (1 << 31) }

// float32 comparisons.

func Eq32(x, y uint32) bool { return feq32(x, y) }
func Ne32(x, y uint32) bool { return !feq32(x, y) }
func Lt32(x, y uint32) bool { return fgt32(y, x) }
func Le32(x, y uint32) bool { return fge32(y, x) }
func Gt32(x, y uint32) bool { return fgt32(x, y) }
func Ge32(x, y uint32) bool { return fge32(x, y) }

// Conversions. Integer operands narrower than 64 bits are first converted
// to int64/uint64 by the front end; results narrower than 64 bits are
// converted from int64/uint64 after the call.

func F64to32(x uint64) uint32     { return f64to32(x) }
func F32to64(x uint32) uint64     { return f32to64(x) }
func Int64to64(x int64) uint64    { return fint64to64(x) }
func Int64to32(x int64) uint32    { return fint64to32(x) }
func Uint64to64(x uint64) uint64  { return fuint64to64(x) }
func Uint64to32(x uint64) uint32  { return fuint64to32(x) }
func F64toInt64(x uint64) int64   { return f64toint64(x) }
func F32toInt64(x uint32) int64   { return f32toint64(x) }
func F64toUint64(x uint64) uint64 { return toUint64(x) }
func F32toUint64(x uint32) uint64 { return toUint64(f32to64(x)) }

// toUint64 converts like amd64 code generated by gc for in-range values.
// (runtime.f64touint64 negates the bit pattern of 2^63 with integer
// negation, which is not a float negation.)
func toUint64(x uint64) uint64 {
	const m uint64 = 0x43e0000000000000 // float64 1<<63
	if fgt64(m, x) {
		return uint64(f64toint64(x))
	}
	return uint64(f64toint64(fsub64(x, m))) | (1 << 63)
}

// min and max builtins: NaN if any operand is NaN, and -0 < +0.

func Min64(x, y uint64) uint64 {
	switch {
	case isNaN64(x):
		return x
	case isNaN64(y):
		return y
	case x|y == 1<<63 && x != y: // -0 and +0
		return 1 << 63
	case fgt64(x, y):
		return y
	}
	return x
}

func Max64(x, y uint64) uint64 {
	switch {
	case isNaN64(x):
		return x
	case isNaN64(y):
		return y
	case x|y == 1<<63 && x != y:
		return 0
	case fgt64(y, x):
		return y
	}
	return x
}

func Min32(x, y uint32) uint32 { return f64to32(Min64(f32to64(x), f32to64(y))) }
func Max32(x, y uint32) uint32 { return f64to32(Max64(f32to64(x), f32to64(y))) }

func isNaN64(x uint64) bool { return x&inf64 == inf64 && x&(1<<mantbits64-1) != 0 }

// print and println of floats, and float panic values: Go 1.27's
// runtime.printfloat64/32 (strconv.AppendFloat 'g' -1) returning the text.
// The front end lowers each float argument of print/println to a call of
// these; the emitter calls them to print a float panic value.

func PrintFloat64(v uint64) string {
	return string(strconv.AppendFloat(nil, math.Float64frombits(v), 'g', -1, 64))
}

func PrintFloat32(v uint32) string {
	return string(strconv.AppendFloat(nil, math.Float64frombits(f32to64(v)), 'g', -1, 32))
}
