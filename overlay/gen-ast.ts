// Generates overlay/tsgo/internal/ast/{ast_generated,utilities}.go from
// typescript-go's originals, with switches on node kinds turned into tables
// indexed by Kind. go/ssa lowers a switch to a chain of comparisons, so a
// kind near the end of many cases (or one that falls to `default`) costs
// two ops per case; a table lookup is a few ops.
// - (*Node).ForEachChild (~200 cases; every leaf kind fell through all of
//   them): each table entry is exactly the original case's body, kinds
//   without a case get nil (the original's default: false).
// - Kind predicates of the form `switch kind { case K1, ..., Kn: return
//   true }; return false` (on a Kind or on node.Kind) with at least
//   MIN_CASES kinds: a [KindCount]bool table with exactly those kinds.
//   node overlay/gen-ast.ts [--tsgo-dir DIR]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { tsgoDir } from "./gen.ts";

const here = dirname(fileURLToPath(import.meta.url));
const astDir = join(tsgoDir(), "internal/ast");
const MIN_CASES = 4;

/** Kind predicates with a switch become table lookups (see the header). */
function predicates(src: string): { out: string; n: number } {
  const re =
    /func (\w+)\((\w+) (Kind|\*Node)\) bool \{\n\tswitch (\w+(?:\.Kind)?) \{\n\tcase ([^:]+):\n\t\treturn true\n\t\}\n\treturn false\n\}\n/g;
  let n = 0;
  const out = src.replace(
    re,
    (all, name: string, param: string, type: string, subj: string, cases: string) => {
      const kinds = cases.split(",").map((k) => k.trim());
      if (subj !== (type === "Kind" ? param : `${param}.Kind`)) return all;
      if (kinds.length < MIN_CASES || !kinds.every((k) => /^Kind\w+$/.test(k))) return all;
      n++;
      const t = `${name}Table`;
      return (
        `func ${name}(${param} ${type}) bool {\n` +
        `\t// go-in-types overlay: a table lookup instead of a switch (gen-ast.ts).\n` +
        `\tk := int(${subj})\n` +
        `\treturn k >= 0 && k < len(${t}) && ${t}[k]\n}\n\n` +
        `// ${t}[k]: k is one of the original switch's kinds.\nvar ${t} [KindCount]bool\n\n` +
        `func init() {\n${kinds.map((k) => `\t${t}[${k}] = true`).join("\n")}\n}\n`
      );
    },
  );
  return { out, n };
}

const header = (file: string, what: string) =>
  "// Code generated by overlay/gen-ast.ts; DO NOT EDIT.\n" +
  `// go-in-types overlay of internal/ast/${file} (typescript-go v7.0.2): ${what}\n` +
  "// through tables indexed by Kind instead of switches (chains of comparisons in SSA).\n\n";

const src = readFileSync(join(astDir, "ast_generated.go"), "utf8");

const head = "func (n *Node) ForEachChild(v Visitor) bool {\n\tswitch n.Kind {\n";
const start = src.indexOf(head);
if (start < 0) throw new Error("ForEachChild switch not found");
const tail = "\tdefault:\n\t\treturn false\n\t}\n}\n";
const end = src.indexOf(tail, start);
if (end < 0) throw new Error("ForEachChild default not found");
const body = src
  .slice(start + head.length, end)
  .split("\n")
  .filter((l) => l !== "");
const entries: string[] = [];
for (let i = 0; i < body.length; i += 2) {
  const c = /^\tcase (Kind\w+(?:, Kind\w+)*):$/.exec(body[i]!);
  const r = /^\t\treturn n\.data\.\(\*(\w+)\)\.ForEachChild\(v\)$/.exec(body[i + 1] ?? "");
  if (!c || !r) throw new Error(`unexpected ForEachChild case: ${body[i]} / ${body[i + 1]}`);
  for (const k of c[1]!.split(", "))
    entries.push(
      `\tforEachChildTable[${k}] = func(n *Node, v Visitor) bool { return n.data.(*${r[1]}).ForEachChild(v) }`,
    );
}

const table = `func (n *Node) ForEachChild(v Visitor) bool {
	// go-in-types overlay: a table lookup instead of the switch (see the header).
	if k := int(n.Kind); k >= 0 && k < len(forEachChildTable) {
		if f := forEachChildTable[k]; f != nil {
			return f(n, v)
		}
	}
	return false
}

// forEachChildTable[k] is the original switch's case for kind k (nil: default).
var forEachChildTable [KindCount]func(n *Node, v Visitor) bool

func init() {
${entries.join("\n")}
}
`;

const gen = predicates(
  src.slice(0, start).replace(/^\/\/ Code generated by .*\n\n?/, "") +
    table +
    src.slice(end + tail.length),
);
const dst = join(here, "tsgo/internal/ast/ast_generated.go");
mkdirSync(dirname(dst), { recursive: true });
writeFileSync(
  dst,
  header("ast_generated.go", "(*Node).ForEachChild and kind predicates") + gen.out,
);
console.log(`wrote ${dst} (ForEachChild: ${entries.length} kinds; ${gen.n} predicates)`);

const util = predicates(readFileSync(join(astDir, "utilities.go"), "utf8"));
const udst = join(here, "tsgo/internal/ast/utilities.go");
writeFileSync(udst, header("utilities.go", "kind predicates") + util.out);
console.log(`wrote ${udst} (${util.n} predicates)`);
