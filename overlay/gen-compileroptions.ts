// Generates the reflection-free CompilerOptions overlays of typescript-go:
//   overlay/tsgo/internal/core/compileroptions.go        (Clone without reflect)
//   overlay/tsgo/internal/tsoptions/parsinghelpers.go    (mergeCompilerOptions without reflect)
// from the originals: the reflect loops become field-by-field code over the
// fields of `type CompilerOptions struct`.
//   node overlay/gen-compileroptions.ts [--tsgo-dir DIR]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { tsgoDir } from "./gen.ts";

const here = dirname(fileURLToPath(import.meta.url));
const src = tsgoDir();

interface FieldInfo {
  name: string;
  type: string;
  json: string;
}

function fields(core: string): FieldInfo[] {
  const start = core.indexOf("type CompilerOptions struct {");
  const end = core.indexOf("\n}\n", start);
  const out: FieldInfo[] = [];
  for (const line of core.slice(start, end).split("\n").slice(1)) {
    const m = /^\t([A-Za-z_]\w*)\s+(.+?)\s+`json:"([^"]*)"`\s*$/.exec(line);
    if (!m) continue;
    out.push({ name: m[1]!, type: m[2]!, json: m[3]!.split(",")[0]! });
  }
  return out;
}

/** Go expression: is field f of x non-zero (reflect.Value.IsZero negated)? */
function nonZero(x: string, f: FieldInfo, pkg: string): string {
  const t = f.type;
  if (t.startsWith("*") || t.startsWith("[]") || t.startsWith("map[")) return `${x}.${f.name} != nil`;
  if (t === "string") return `${x}.${f.name} != ""`;
  if (t === "bool") return `${x}.${f.name}`;
  // Named integer types of package core (Tristate, ModuleKind, ...).
  if (/^[A-Z]\w*$/.test(t) || /^core\.[A-Z]\w*$/.test(t)) return `${x}.${f.name} != 0`;
  throw new Error(`unhandled field type ${t} of ${f.name} (${pkg})`);
}

const header = (what: string) =>
  `// Code generated by overlay/gen-compileroptions.ts; DO NOT EDIT.\n// go-in-types overlay of ${what} (typescript-go v7.0.2): field-by-field code\n// instead of reflect.\n\n`;

function replaceBetween(s: string, from: string, to: string, by: string): string {
  const i = s.indexOf(from);
  const j = s.indexOf(to, i);
  if (i < 0 || j < 0) throw new Error(`marker not found: ${from}`);
  return s.slice(0, i) + by + s.slice(j + to.length);
}

const coreFile = readFileSync(join(src, "internal/core/compileroptions.go"), "utf8");
const fs = fields(coreFile);
if (fs.length < 100) throw new Error(`only ${fs.length} CompilerOptions fields found`);

// core.Clone: copy every exported field.
let core = replaceBetween(
  coreFile,
  "var optionsType = reflect.TypeFor[CompilerOptions]()",
  "\treturn target\n}\n",
  "func (options *CompilerOptions) Clone() *CompilerOptions {\n\ttarget := &CompilerOptions{}\n" +
    fs.map((f) => `\ttarget.${f.name} = options.${f.name}\n`).join("") +
    "\treturn target\n}\n",
);
core = core.replace('\t"reflect"\n', "");
// The doc comment of Clone sat between the var and the func; keep the file tidy.
mkdirSync(join(here, "tsgo/internal/core"), { recursive: true });
writeFileSync(join(here, "tsgo/internal/core/compileroptions.go"), header("internal/core/compileroptions.go") + core);

// tsoptions.mergeCompilerOptions: explicit nulls zero a field, else copy non-zero fields.
const phFile = readFileSync(join(src, "internal/tsoptions/parsinghelpers.go"), "utf8");
let ph = replaceBetween(
  phFile,
  "\ttargetValue := reflect.ValueOf(targetOptions).Elem()",
  "\treturn targetOptions\n}\n",
  fs
    .map(
      (f) =>
        `\tif explicitNullFields.Has(${JSON.stringify(f.json)}) {\n` +
        `\t\ttargetOptions.${f.name} = (&core.CompilerOptions{}).${f.name}\n` +
        `\t} else if ${nonZero("sourceOptions", f, "tsoptions")} {\n` +
        `\t\ttargetOptions.${f.name} = sourceOptions.${f.name}\n\t}\n`,
    )
    .join("") + "\n\treturn targetOptions\n}\n",
);
if (!/\breflect\./.test(ph)) ph = ph.replace('\t"reflect"\n', "");
mkdirSync(join(here, "tsgo/internal/tsoptions"), { recursive: true });
writeFileSync(join(here, "tsgo/internal/tsoptions/parsinghelpers.go"), header("internal/tsoptions/parsinghelpers.go") + ph);
console.log(`generated Clone and mergeCompilerOptions for ${fs.length} fields`);
