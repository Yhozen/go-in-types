// H5 cost test for maps (src/types/map.ts) and per-op costs of strings
// (src/types/str.ts), on stock tsrs. Map ops run in an alias-argument loop
// over a heap of 256 + N live objects holding a map of S entries (built by
// the codec, src/types/codec-map.ts); cost per op is (inst(2K) - inst(K)) / K.
//
//   scripts/heavy.sh node scripts/cost-map.ts [--k 100] [--n 0,1024,10240,102400]
//       [--s 10,1000,10000] [--ops lookup,...] [--str] [--out .run/cost-map.json]
//
// Part 1: S = 1000, every N (must be flat in N). Part 2: N = 0, every S (may
// grow at most logarithmically in S). --str adds the string table. Exit 1 if
// a cost grows with N or a run fails.
import { spawn } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { GoMap } from "../src/ref/gomap.ts";
import { encodeInt64 } from "../src/types/codec-int.ts";
import { mapStateToType, type MapKeyCodec } from "../src/types/codec-map.ts";
import { strToType } from "../src/types/codec-str.ts";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const opt = (k: string, d: string) => {
  const i = argv.indexOf(`--${k}`);
  return i >= 0 ? argv[i + 1]! : d;
};
const K = Number(opt("k", "100"));
const NS = opt("n", "0,1024,10240,102400").split(",").map(Number);
const SS = opt("s", "10,1000,10000").split(",").map(Number);
const outFile = opt("out", join(repo, ".run/cost-map.json"));
const tsrs = opt("tsrs", join(repo, "node_modules/.bin/tsrs"));
const work = join(repo, ".run/cost-map");
mkdirSync(work, { recursive: true });

const HEX = "0123456789abcdef";
const hex = (v: number, w: number) => v.toString(16).padStart(w, "0");
const range = (n: number) => Array.from({ length: n }, (_, i) => i);
const q = (s: string) => JSON.stringify(s);
const int = (n: number | bigint) => q(encodeInt64(BigInt(n)));

/** Identifier-like keys of 8-20 bytes. */
const key = (i: number) => `id_${(i * 2654435761) % 1000003}_${"abcdefgh".slice(0, i % 8)}`;
const newKey = (i: number) => `nw_${i}_q`;

const strKeys: MapKeyCodec = {
  mode: "s",
  canon: (k) => k as string,
  keyText: (k) => strToType(k as string),
  keyFrom: (t) => t,
};
const intKeys: MapKeyCodec = {
  mode: "i",
  canon: (k) => encodeInt64(BigInt(k as number)),
  keyText: (k) => int(k as number),
  keyFrom: (t) => t,
};
const names = { mk6: "M.MapMk6", mk5: "M.MapMk5", mk16: "M.MapMk16" };

function mapState(s: number, ints: boolean): string {
  const m = new GoMap(0, (k) => k);
  for (let i = 0; i < s; i++) m.set(ints ? i * 7 : key(i), "v" + i);
  return mapStateToType(
    m,
    ints ? intKeys : strKeys,
    { valText: (v) => q(v as string), valFrom: (t) => t },
    names,
  );
}

interface Op {
  h?: string;
  a?: string;
  a0?: string;
}
// In scope: H, I, A; KS = existing string key, KI = existing int key, KN = new key, KH = hot key, V = value.
const ops: Record<string, Op> = {
  none: {},
  lookup: { a: `M.MapLookup<H, "00001", KS, "z">` },
  lookupHot: { a: `M.MapLookup<H, "00001", KH, "z">` },
  lookupInt: { a: `M.MapLookup<H, "00002", KI, "z">` },
  lookupOk: { a: `M.MapLookupOk<H, "00001", KS, "z">` },
  update: { h: `M.MapUpdate<H, "00001", KS, KS, V>` },
  insert: { h: `M.MapUpdate<H, "00001", KN, KN, V>` },
  delete: { h: `M.MapDelete<H, "00001", KS>` },
  delIns: { h: `M.MapUpdate<M.MapDelete<H, "00001", KS>, "00001", KS, KS, V>` },
  next: { a: `NextIt<M.MapNext<H, "00001", A & string, 0, 0>>`, a0: q("0") },
  len: { a: `M.MapLen<H, "00001">` },
};

function generate(op: string, n: number, s: number, k: number): string {
  const o = ops[op]!;
  const out: string[] = [];
  const w = (x: string) => out.push(x);
  w(`// GENERATED by scripts/cost-map.ts ${JSON.stringify({ op, n, s, k })}`);
  w(`import type * as H from "../../src/types/heap.ts";`);
  w(`import type * as M from "../../src/types/map.ts";`);
  w(`import type { E2, E3, E4, Mk16 } from "../../src/types/heap.gen.ts";`);
  w(`export {};`);
  w(`type Obj<Id extends string> = H.Flat<Id, \`v\${Id}\`, "0", "0", "0", "0", "0", "0">;`);
  w(`type MS1 = ${mapState(s, false)};`);
  w(`type MS2 = ${mapState(s, true)};`);
  w(
    `type Full1<Q extends string> = Mk16<${HEX.split("")
      .map((d) => `Obj<\`\${Q}${d}\`>`)
      .join(", ")}>;`,
  );
  w(
    `type Full2<P extends string> = Mk16<${HEX.split("")
      .map((d) => `Full1<\`\${P}${d}\`>`)
      .join(", ")}>;`,
  );
  w(
    `type B0 = Mk16<Mk16<Obj<"00000">, MS1, MS2, ${range(13)
      .map((i) => `Obj<"0000${HEX[i + 3]}">`)
      .join(", ")}>, ${range(15)
      .map((i) => `Full1<"000${HEX[i + 1]}">`)
      .join(", ")}>;`,
  );
  const blocks = 1 + n / 256;
  for (let b = 0; b < blocks; b++)
    w(b === 0 ? `type B_000 = B0;` : `type B_${hex(b, 3)} = Full2<"${hex(b, 3)}">;`);
  const has = (p: string) => parseInt(p.padEnd(3, "0"), 16) < blocks;
  for (let a = 0; a < 16; a++)
    for (let b = 0; b < 16; b++) {
      const p = HEX[a]! + HEX[b]!;
      if (has(p))
        w(
          `type L_${p} = Mk16<${HEX.split("")
            .map((d) => (has(p + d) ? `B_${p}${d}` : "E2"))
            .join(", ")}>;`,
        );
    }
  for (let a = 0; a < 16; a++) {
    const p = HEX[a]!;
    if (has(p))
      w(
        `type L_${p} = Mk16<${HEX.split("")
          .map((d) => (has(p + d) ? `L_${p}${d}` : "E3"))
          .join(", ")}>;`,
      );
  }
  w(
    `type Root = Mk16<${HEX.split("")
      .map((d) => (has(d) ? `L_${d}` : "E4"))
      .join(", ")}>;`,
  );
  w(`type H0 = H.HeapMk<"${hex(blocks * 256, 5)}", Root>;`);
  const tok = (i: number) => (i >= k ? "end" : `s${i}`);
  const tab = (name: string, f: (i: number) => string) =>
    w(
      `interface ${name} { ${range(k)
        .map((i) => `${tok(i)}: ${f(i)};`)
        .join(" ")} }`,
    );
  tab("Seq", (i) => q(tok(i + 1)));
  tab("KST", (i) => strToType(key(i % s)));
  tab("KIT", (i) => int((i % s) * 7));
  tab("KNT", (i) => strToType(newKey(i)));
  tab("KHT", (i) => strToType(key(i % Math.min(8, s))));
  tab("VT", (i) => q(`w${i}`));
  w(`type At<T, I> = I extends keyof T ? T[I] : never;`);
  w(`type NextIt<R> = R["0" & keyof R] extends true ? R["3" & keyof R] : "0";`);
  const sub = (x: string) =>
    x
      .replace(/\bKS\b/g, "(At<KST, I> & string)")
      .replace(/\bKI\b/g, "(At<KIT, I> & string)")
      .replace(/\bKN\b/g, "(At<KNT, I> & string)")
      .replace(/\bKH\b/g, "(At<KHT, I> & string)")
      .replace(/\bV\b/g, "At<VT, I>");
  w(
    `type Loop<H, I, A> = I extends "end" ? [H, A] : Loop<${o.h ? sub(o.h) : "H"}, At<Seq, I>, ${o.a ? sub(o.a) : "A"}>;`,
  );
  w(`type Res = Loop<H0, "s0", ${o.a0 ?? q("x")}>;`);
  w(`type IsAnyOrNever<T> = [T] extends [never] ? true : 0 extends 1 & T ? true : false;`);
  w(
    `export const notAny: [false, false] = null! as [IsAnyOrNever<Res[1]>, IsAnyOrNever<M.MapLen<Res[0], "00001">>];`,
  );
  return out.join("\n") + "\n";
}

// ---------------------------------------------------------------- strings

const ALPHA = "abcdefghijklmnopqrstuvwxyz_0123456789 ;(){}\n";
let seed = 99;
const rnd = () => {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x80000000;
};
const text = (n: number) =>
  range(n)
    .map(() => ALPHA[Math.floor(rnd() * ALPHA.length)])
    .join("");
const LONG = text(20000);
const MB = range(3000)
  .map((i) => String.fromCharCode(0xe2, 0x82, 0x80 + (i % 40)))
  .join("");

/** String ops: [setup lines, expression with I in scope]. Inputs are distinct per step unless noted. */
const strOps: Record<string, { tab?: (i: number) => string; e: string }> = {
  none: { e: `A` },
  lenShort: { tab: (i) => strToType(key(i)), e: `S.Len<X>` },
  lenLong: { tab: (i) => strToType(i + LONG.slice(0, 4000)), e: `S.Len<X>` },
  indexShort: { tab: (i) => strToType(key(i)), e: `S.Index<X, "5">` },
  indexLong: { tab: (i) => int((i * 197) % 20000), e: `S.Index<L, X>` },
  sliceLong: { tab: (i) => int((i * 197) % 19000), e: `S.Slice<L, X, AddT<X>>` },
  sliceShort: { tab: (i) => strToType(key(i)), e: `S.Slice<X, "2", "6">` },
  compare: { tab: (i) => strToType(key(i)), e: `S.Compare<X, "id_5000_abcd">` },
  eq: { tab: (i) => strToType(key(i)), e: `S.Eq<X, "id_5000_abcd">` },
  concat: { tab: (i) => strToType(key(i)), e: `S.Concat<X, "_suffix">` },
  hash: { tab: (i) => strToType(key(i)), e: `M.Hash<X>` },
  nextLong: { tab: (i) => int((i * 197) % 20000), e: `S.Next<L, X>` },
  nextMB: { tab: (i) => int(((i * 37) % 3000) * 3), e: `S.Next<MB, X>` },
  runeStr: { tab: (i) => int(0x400 + i * 331), e: `S.RuneStr<X>` },
  indexByte: { tab: (i) => strToType(key(i) + "\n"), e: `S.IndexByte<X, "a0">` },
};

function generateStr(op: string, k: number): string {
  const o = strOps[op]!;
  const out: string[] = [];
  const w = (x: string) => out.push(x);
  w(`// GENERATED by scripts/cost-map.ts ${JSON.stringify({ op, k })}`);
  w(`import type * as S from "../../src/types/str.ts";`);
  w(`import type * as M from "../../src/types/map.ts";`);
  w(`export {};`);
  w(`type L = ${strToType(LONG)};`);
  w(`type MB = ${strToType(MB)};`);
  // warm the long strings' indexes outside the loop (the first access builds them)
  w(`export type Warm = [S.Index<L, "0">, S.Index<MB, "0">];`);
  const tok = (i: number) => (i >= k ? "end" : `s${i}`);
  w(
    `interface Seq { ${range(k)
      .map((i) => `${tok(i)}: ${q(tok(i + 1))};`)
      .join(" ")} }`,
  );
  w(
    `interface XT { ${range(k)
      .map((i) => `${tok(i)}: ${o.tab ? o.tab(i) : '""'};`)
      .join(" ")} }`,
  );
  w(
    `interface AddT_ { ${range(k)
      .map((i) => `${tok(i)}: ${int(((i * 197) % 19000) + 10)};`)
      .join(" ")} }`,
  );
  w(`type At<T, I> = I extends keyof T ? T[I] : never;`);
  w(
    `type Loop<I, A> = I extends "end" ? A : Loop<At<Seq, I>, ${o.e.replace(/AddT<X>/g, "(At<AddT_, I> & string)").replace(/\bX\b/g, "(At<XT, I> & string)")}>;`,
  );
  w(`type Res = Loop<"s0", "x">;`);
  w(`type IsAnyOrNever<T> = [T] extends [never] ? true : 0 extends 1 & T ? true : false;`);
  w(`export const notAny: false = null! as IsAnyOrNever<Res>;`);
  return out.join("\n") + "\n";
}

// ---------------------------------------------------------------- running

type Run = { inst: number; mem: number; check: number; errors: string };
function runOne(file: string): Promise<Run> {
  return new Promise((res) => {
    const p = spawn(
      tsrs,
      [
        "--ignoreConfig",
        "--fast",
        "--singleThreaded",
        "--extendedDiagnostics",
        "--noEmit",
        "--types",
        "",
        "--lib",
        "es2023",
        "--strict",
        "--module",
        "nodenext",
        "--allowImportingTsExtensions",
        file,
      ],
      { env: { ...process.env, TSRS_FAST: "1" } },
    );
    let out = "";
    p.stdout.on("data", (d) => (out += d));
    p.stderr.on("data", (d) => (out += d));
    const timer = setTimeout(() => p.kill("SIGKILL"), 600_000);
    p.on("close", () => {
      clearTimeout(timer);
      const num = (re: RegExp) => Number(out.match(re)?.[1] ?? NaN);
      const inst = num(/^Instantiations:\s+(\d+)/m);
      const errors = out
        .split("\n")
        .filter((l) => /error TS/.test(l))
        .slice(0, 3)
        .join(" | ");
      res({
        inst,
        mem: num(/^Memory used:\s+(\d+)K/m),
        check: num(/^Check time:\s+([\d.]+)s/m),
        errors: Number.isNaN(inst) ? "timeout/crash " + errors : errors,
      });
    });
  });
}

async function pair(name: string, gen: (k: number) => string) {
  const f1 = join(work, `${name}-${K}.ts`);
  const f2 = join(work, `${name}-${2 * K}.ts`);
  writeFileSync(f1, gen(K));
  writeFileSync(f2, gen(2 * K));
  const a = await runOne(f1);
  const b = await runOne(f2);
  const r = {
    name,
    perOp: (b.inst - a.inst) / K,
    errors: [a.errors, b.errors].filter(Boolean).join(" | "),
    check2K: b.check,
    mem2K: b.mem,
  };
  console.error(JSON.stringify(r));
  return r;
}

async function main() {
  const which = opt("ops", Object.keys(ops).join(",")).split(",").filter(Boolean);
  const result: Record<string, unknown> = { k: K };
  let failed = false;
  // Part 1: S = 1000 at every N.
  const p1: Record<string, Awaited<ReturnType<typeof pair>>[]> = {};
  for (const op of which) {
    p1[op] = [];
    for (const n of NS)
      p1[op].push(await pair(`${op}-n${n}-s1000`, (k) => generate(op, n, 1000, k)));
  }
  console.log(
    `\nMap ops, S = 1000 entries, by live heap objects N (instantiations per op, K = ${K}):\n`,
  );
  console.log(`| op | ${NS.map((n) => `N=${n}`).join(" | ")} |`);
  console.log(`| --- | ${NS.map(() => "---:").join(" | ")} |`);
  for (const op of which) {
    const rs = p1[op]!;
    const c0 = rs[0]!.perOp;
    const cells = rs.map((r) => {
      const bad = Boolean(r.errors) || !(r.perOp <= c0 * 1.05 + 12);
      if (bad) failed = true;
      return `${r.perOp}${r.errors ? " ERR" : ""}${bad ? " !" : ""}`;
    });
    console.log(`| ${op} | ${cells.join(" | ")} |`);
  }
  // Part 2: N = 0 at every S.
  const p2: Record<string, Awaited<ReturnType<typeof pair>>[]> = {};
  for (const op of which) {
    p2[op] = [];
    for (const s of SS) p2[op].push(await pair(`${op}-n0-s${s}`, (k) => generate(op, 0, s, k)));
  }
  console.log(`\nMap ops, N = 0, by map size S:\n`);
  console.log(`| op | ${SS.map((s) => `S=${s}`).join(" | ")} |`);
  console.log(`| --- | ${SS.map(() => "---:").join(" | ")} |`);
  for (const op of which) {
    const cells = p2[op]!.map((r) => {
      if (r.errors) failed = true;
      return `${r.perOp}${r.errors ? " ERR" : ""}`;
    });
    console.log(`| ${op} | ${cells.join(" | ")} |`);
  }
  result.byN = p1;
  result.byS = p2;
  if (argv.includes("--str")) {
    const rows = [];
    for (const op of opt("strops", Object.keys(strOps).join(",")).split(","))
      rows.push(await pair(`str-${op}`, (k) => generateStr(op, k)));
    console.log(
      `\nString ops (instantiations per op, distinct inputs per step; long = 20 KB with its index built):\n`,
    );
    console.log(`| op | per op |`);
    console.log(`| --- | ---: |`);
    for (const r of rows) {
      if (r.errors) failed = true;
      console.log(`| ${r.name.slice(4)} | ${r.perOp}${r.errors ? " ERR" : ""} |`);
    }
    result.str = rows;
  }
  writeFileSync(outFile, JSON.stringify(result, null, 2));
  if (failed) {
    console.log("\nFAIL: cost grows with heap size, or a run failed");
    process.exit(1);
  }
}
await main();
