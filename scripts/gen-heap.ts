/** Canonical int encoding of a non-negative number (lowercase nibbles, LSB first, sign nibble when needed). */
export function nib(n: number): string {
  if (n === 0) return "0";
  let s = "";
  while (n > 0) {
    s += HEX[n % 16];
    n = Math.floor(n / 16);
  }
  if (parseInt(s[s.length - 1]!, 16) >= 8) s += "0";
  return s;
}

