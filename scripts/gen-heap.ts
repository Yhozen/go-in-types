// Writes src/types/heap.gen.ts: lookup tables and the regular trie plumbing
// of the type-level heap (src/types/heap.ts) and its index arithmetic
// (src/types/nat.ts). Run: node scripts/gen-heap.ts [--width 5]
//
// Width W is the number of hex digits of an object id (16^W ids). The
// default 5 gives ~1M objects; a wider heap is this file regenerated.
