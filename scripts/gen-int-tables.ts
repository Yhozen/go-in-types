// Generate the lookup tables of the type-level integers (src/types/int.ts):
//
//   node scripts/gen-int-tables.ts     ->  src/types/int-tables.gen.ts
//
// Adapted from lua-in-types' scripts/gen-aot-int64-tests.ts (tables part):
// Go's division truncates, so the one-nibble quotient tables differ, and the
// unsigned and width tables are new.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { encodeInt64 } from "../src/types/codec-int.ts";

const ROOT = resolve(import.meta.dirname, "..");
export const TABLES_PATH = resolve(ROOT, "src/types/int-tables.gen.ts");
const HEADER = `// Generated by scripts/gen-int-tables.ts. Do not edit.\n`;

const hex = (n: number) => n.toString(16);
const lit = (s: string) => JSON.stringify(s);
const N16 = Array.from({ length: 16 }, (_, i) => i);
const enc = (x: bigint) => encodeInt64(BigInt.asIntN(64, x));

type Entries = [string, string][];

/**
 * Tables tested with `K extends keyof T` (membership). Every other table gets
 * a string index signature, so lookups with generic keys need no `& keyof T`.
 */
const MEMBERSHIP = new Set(["SHAMT", "POW2", "TODEC", "UDEC8", "SMALL"]);

function table(name: string, doc: string, entries: Entries, raw?: string): string {
  const sig = MEMBERSHIP.has(name) ? [] : [`  [key: string]: ${raw ?? "string"};`];
  const body = [...sig, ...entries.map(([k, v]) => `  ${lit(k)}: ${raw ? v : lit(v)};`)].join("\n");
  return `/** ${doc} */\nexport type ${name} = {\n${body}\n};\n`;
}

const pairs = (f: (a: number, b: number) => string | undefined): Entries => {
  const out: Entries = [];
  for (const a of N16)
    for (const b of N16) {
      const v = f(a, b);
      if (v !== undefined) out.push([hex(a) + hex(b), v]);
    }
  return out;
};

/** Signed value of a single canonical nibble (-8..7). */
const s1 = (a: number) => (a >= 8 ? a - 16 : a);
/** Unsigned value of a one-nibble canonical form as a 64-bit pattern. */
const u1 = (a: number) => BigInt.asUintN(64, BigInt(s1(a)));

export function tablesSource(): string {
  const t: string[] = [];
  const carry = (f: (c: number, a: number, b: number) => [number, number]) => {
    const out: Entries = [];
    for (const c of [0, 1])
      for (const a of N16)
        for (const b of N16) {
          const [d, c2] = f(c, a, b);
          out.push([`${c}${hex(a)}${hex(b)}`, `${hex(d)}${c2}`]);
        }
    return out;
  };
  t.push(
    table(
      "ADD",
      "`${carry}${a}${b}` -> `${digit}${carry}` of a + b + carry.",
      carry((c, a, b) => [(a + b + c) & 15, (a + b + c) >> 4]),
    ),
    table(
      "SUB",
      "`${borrow}${a}${b}` -> `${digit}${borrow}` of a - b - borrow.",
      carry((c, a, b) => [(a - b - c) & 15, a - b - c < 0 ? 1 : 0]),
    ),
    table(
      "NOT",
      "~a.",
      N16.map((a) => [hex(a), hex(15 - a)]),
    ),
    table(
      "AND",
      "`${a}${b}` -> a & b.",
      pairs((a, b) => hex(a & b)),
    ),
    table(
      "OR",
      "`${a}${b}` -> a | b.",
      pairs((a, b) => hex(a | b)),
    ),
    table(
      "XOR",
      "`${a}${b}` -> a ^ b.",
      pairs((a, b) => hex(a ^ b)),
    ),
    table(
      "EXT",
      'a -> its sign extension: "f" when the top bit is set, else "0".',
      N16.map((a) => [hex(a), a >= 8 ? "f" : "0"]),
    ),
    table(
      "ADDE",
      "`${carry}${ea}${eb}` -> the digit of ea + eb + carry for sign extensions ea, eb.",
      carry((c, a, b) => [(a + b + c) & 15, 0])
        .filter(([k]) => /^.[0f][0f]$/.test(k))
        .map(([k, v]) => [k, v[0]!]),
    ),
    table(
      "SUBE",
      "`${borrow}${ea}${eb}` -> the digit of ea - eb - borrow for sign extensions ea, eb.",
      carry((c, a, b) => [(a - b - c) & 15, 0])
        .filter(([k]) => /^.[0f][0f]$/.test(k))
        .map(([k, v]) => [k, v[0]!]),
    ),
    table(
      "SUCC",
      "a + 1 for a < 15.",
      N16.slice(0, 15).map((a) => [hex(a), hex(a + 1)]),
    ),
  );
  const mulc: Entries = [];
  for (const a of N16)
    for (const b of N16)
      for (const c of N16) {
        const v = a * b + c;
        mulc.push([hex(a) + hex(b) + hex(c), hex(v & 15) + hex(v >> 4)]);
      }
  t.push(table("MULC", "`${a}${b}${c}` -> `${lo}${hi}` of a * b + c.", mulc));
  const addh: Entries = [];
  for (const lo of N16)
    for (const x of N16)
      for (const hi of N16) {
        const s = lo + x;
        if (hi + (s >> 4) <= 15)
          addh.push([hex(lo) + hex(x) + hex(hi), hex(s & 15) + hex(hi + (s >> 4))]);
      }
  t.push(
    table(
      "ADDH",
      "`${lo}${x}${hi}` -> `${digit}${carry}` of lo + x, carry = hi + (lo + x >> 4) (multiply rows).",
      addh,
    ),
  );
  const div1: Entries = [];
  for (const d of N16.slice(1))
    for (let r = 0; r < d; r++)
      for (const n of N16) {
        const v = r * 16 + n;
        div1.push([hex(r) + hex(n) + hex(d), hex(Math.floor(v / d)) + hex(v % d)]);
      }
  t.push(table("DIV1", "`${r}${n}${d}` -> `${q}${r}` of (16 r + n) / d, for r < d.", div1));
  const shl: Entries = [];
  const shr: Entries = [];
  for (const r of [1, 2, 3])
    for (const a of N16)
      for (const b of N16) {
        shl.push([`${r}${hex(a)}${hex(b)}`, hex(((b << r) | (a >> (4 - r))) & 15)]);
        shr.push([`${r}${hex(a)}${hex(b)}`, hex(((a >> r) | (b << (4 - r))) & 15)]);
      }
  t.push(
    table("SHL", "`${r}${prev}${a}` -> nibble a shifted left r bits, filled from prev.", shl),
    table("SHR", "`${r}${a}${next}` -> nibble a shifted right r bits, filled from next.", shr),
    table(
      "SHAMT",
      "Canonical 0..63 -> `${q}${r}`: a shift by 4 q + r bits.",
      Array.from({ length: 64 }, (_, n) => [enc(BigInt(n)), hex(n >> 2) + String(n & 3)]),
    ),
    table(
      "POW2",
      "Canonical 2^k (k = 1..62) -> `${q}${r}` with k = 4 q + r (multiply, divide by shifts).",
      Array.from({ length: 62 }, (_, i) => [
        enc(1n << BigInt(i + 1)),
        hex((i + 1) >> 2) + String((i + 1) & 3),
      ]),
    ),
    table(
      "POW2M1",
      "Canonical 2^k -> 2^k - 1 (modulo by a mask, rounding a negative quotient toward zero).",
      Array.from({ length: 62 }, (_, i) => [
        enc(1n << BigInt(i + 1)),
        enc((1n << BigInt(i + 1)) - 1n),
      ]),
    ),
    table(
      "ZEROS",
      "q -> q zero nibbles.",
      N16.map((q) => [hex(q), "0".repeat(q)]),
    ),
  );
  const d16: Entries = [];
  for (let x = 0; x < 10; x++)
    for (const c of N16) {
      const v = x * 16 + c;
      d16.push([`${x}${hex(c)}`, `${v % 10}${hex(Math.floor(v / 10))}`]);
    }
  t.push(
    table("D16", "`${x}${c}` -> `${digit}${carry}` of 16 x + c (x decimal, c and carry hex).", d16),
    table(
      "CDEC",
      "A final carry 0..15 -> its decimal digits, least significant first.",
      N16.map((c) => [hex(c), c === 0 ? "" : String(c).split("").reverse().join("")]),
    ),
  );
  // Fast paths: both operands one nibble (-8..7).
  const small = (f: (a: number, b: number) => bigint | undefined): Entries =>
    pairs((a, b) => {
      const v = f(s1(a), s1(b));
      return v === undefined ? undefined : enc(v);
    });
  t.push(
    table(
      "ADD1",
      "One-nibble a + b.",
      small((a, b) => BigInt(a + b)),
    ),
    table(
      "SUB1",
      "One-nibble a - b.",
      small((a, b) => BigInt(a - b)),
    ),
    table(
      "MUL1",
      "One-nibble a * b.",
      small((a, b) => BigInt(a * b)),
    ),
    table(
      "QUO1",
      "One-nibble a / b, truncated (b != 0; -8 / -1 is 8, which fits every width).",
      small((a, b) => (b === 0 ? undefined : BigInt(a) / BigInt(b))),
    ),
    table(
      "REM1",
      "One-nibble a % b, sign of a (b != 0).",
      small((a, b) => (b === 0 ? undefined : BigInt(a) % BigInt(b))),
    ),
    table(
      "LT1",
      "One-nibble a < b, signed.",
      pairs((a, b) => String(s1(a) < s1(b))),
      "boolean",
    ),
    table(
      "ULT1",
      "One-nibble a < b, unsigned (the sign-extended patterns compared as uint64).",
      pairs((a, b) => String(u1(a) < u1(b))),
      "boolean",
    ),
    table(
      "ULT",
      '`${a}${b}` -> "<" or ">" for unsigned nibbles a != b.',
      pairs((a, b) => (a === b ? undefined : a < b ? "<" : ">")),
    ),
    table(
      "NEG1",
      "One-nibble -a.",
      N16.map((a) => [hex(a), enc(BigInt(-s1(a)))]),
    ),
  );
  const decs: Entries = [];
  for (let v = -2048; v < 2048; v++) decs.push([enc(BigInt(v)), String(v)]);
  t.push(
    table("TODEC", "Canonical forms of up to three nibbles (-2048..2047) -> decimal.", decs),
    table(
      "UDEC8",
      "Negative canonical forms of uint8 values (128..255) -> decimal.",
      Array.from({ length: 128 }, (_, i) => [enc(BigInt(i - 128)), String(i + 128)]),
    ),
  );
  // Conversions between kinds: "=" keeps the form, "z" zero-extends the source
  // width, "t" truncates to the target width (sign-extending it).
  const kinds = ["i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64"];
  const conv: Entries = [];
  for (const f of kinds)
    for (const to of kinds) {
      const fw = Number(f.slice(1));
      const tw = Number(to.slice(1));
      conv.push([f + to, tw < fw ? "t" : tw > fw && f[0] === "u" ? "z" : "="]);
    }
  t.push(
    table(
      "CONV",
      '`${from}${to}` -> "=" (same form), "z" (zero-extend from) or "t" (truncate to).',
      conv,
    ),
  );
  return `${HEADER}// Lookup tables of src/types/int.ts. Nibbles are lowercase hex digits.\n\n${t.join("\n")}`;
}

if (import.meta.main) writeFileSync(TABLES_PATH, tablesSource());
