// Generate the type-level integer tests (assertions checked by tsrs):
//
//   node scripts/gen-int-tests.ts   ->  tests/types/int-<kind>.gen.ts, tests/types/int-conv.gen.ts
//
// Expected values come from the reference (scripts/int-ref.ts over
// src/ref/values.ts). Every op x width: edge values (0, +-1, min, max, powers
// of two and their neighbours) paired with each other, plus seeded random
// values; shifts by every count up to past the width with counts of several
// kinds; conversions between every pair of kinds.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import type { BinOpKind, IntKind } from "../src/ir/types.ts";
import { WIDTH, type I64 } from "../src/ref/values.ts";
import { intTag, intToType } from "../src/types/codec-int.ts";
import { KINDS, refBinop, refConv, refUnop, refValue, type RefResult } from "./int-ref.ts";

const ROOT = resolve(import.meta.dirname, "..");
const HEADER = `// Generated by scripts/gen-int-tests.ts. Do not edit.\n`;
const lit = (s: string) => JSON.stringify(s);

/** Deterministic pseudo-random numbers (mulberry32). */
export const rng = (seed: number) => () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

/** A random value of 1..w significant bits, either sign, as a reference value of kind k. */
export function randomValue(random: () => number, k: IntKind): I64 {
  const w = WIDTH[k];
  const bits = 1 + Math.floor(random() * w);
  let x = 1n;
  for (let i = 1; i < bits; i++) x = (x << 1n) | (random() < 0.5 ? 1n : 0n);
  return refValue(random() < 0.5 ? -x : x, k);
}

/** Edge values of kind k: 0, +-1, +-2, min, max and neighbours, powers of two +-1. */
export function edges(k: IntKind): I64[] {
  const w = BigInt(WIDTH[k]);
  const set = new Set<bigint>([0n, 1n, -1n, 2n, -2n, 7n, 8n, -8n, -9n, 10n, 16n]);
  for (let j = 3n; j < w; j += 4n) for (const d of [-1n, 0n, 1n]) set.add((1n << j) + d);
  for (const d of [-1n, 0n, 1n]) set.add((1n << (w - 1n)) + d).add((1n << w) + d);
  const out = new Map<string, I64>();
  for (const x of set) {
    const v = refValue(x, k);
    out.set(String(v), v);
  }
  return [...out.values()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** A spread subset of the edges for the quadratic pairings. */
function core(k: IntKind): I64[] {
  const w = BigInt(WIDTH[k]);
  const xs = [0n, 1n, -1n, 2n, 7n, 8n, -8n, 127n, 128n, -129n, 255n, 0x1234n];
  xs.push((1n << (w - 1n)) - 1n, 1n << (w - 1n), (1n << (w - 1n)) + 1n);
  if (w >= 32n) xs.push(0x12345678n, -(1n << 31n), 1n << 32n);
  if (w === 64n) xs.push(0x123456789abcdefn, -0x0fedcba987654321n);
  const out = new Map<string, I64>();
  for (const x of xs) {
    const v = refValue(x, k);
    out.set(String(v), v);
  }
  return [...out.values()];
}

const ARITH: BinOpKind[] = ["+", "-", "*", "/", "%", "&", "|", "^", "&^"];
const CMP: BinOpKind[] = ["==", "!=", "<", "<=", ">", ">="];
export const OPNAME: Record<string, string> = {
  "+": "Add",
  "-": "Sub",
  "*": "Mul",
  "/": "Quo",
  "%": "Rem",
  "&": "And",
  "|": "Or",
  "^": "Xor",
  "&^": "AndNot",
  "<<": "Shl",
  ">>": "Shr",
  "==": "Eq",
  "!=": "Ne",
  "<": "Lt",
  "<=": "Le",
  ">": "Gt",
  ">=": "Ge",
};

/** The expected type of a reference result of kind k. */
export function expected(r: RefResult, k: IntKind): string {
  if (typeof r === "boolean") return String(r);
  if (typeof r === "object") return `["panic", ${lit(r.panic)}]`;
  return lit(intToType(r, k));
}

/** The type expression of a binop on kind-k values (shift counts of kind ck). */
export function binExpr(op: BinOpKind, k: IntKind, a: I64, b: I64, ck: IntKind = k): string {
  const A = lit(intToType(a, k));
  const name = OPNAME[op]!;
  if (op === "==" || op === "!=") return `I.${name}<${A}, ${lit(intToType(b, k))}>`;
  if (op === "<<" || op === ">>")
    return `I.${name}<${lit(intTag(k))}, ${A}, ${lit(intTag(ck))}, ${lit(intToType(b, ck))}>`;
  return `I.${name}<${lit(intTag(k))}, ${A}, ${lit(intToType(b, k))}>`;
}

class Cases {
  lines: string[] = [];
  check(expr: string, exp: string) {
    this.lines.push(`export type T${this.lines.length} = Assert<Equal<${expr}, ${exp}>>;`);
  }
  source(): string {
    return `${HEADER}import type * as I from "../../src/types/int.ts";

/** Exact type equality (any, unions and never all compare strictly). */
type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;
type Assert<T extends true> = T;

${this.lines.join("\n")}
`;
  }
}

function kindTests(k: IntKind, seed: number): Cases {
  const random = rng(seed);
  const c = new Cases();
  const tag = lit(intTag(k));
  const E = edges(k);
  const C = core(k);
  const pairs: [I64, I64][] = [];
  for (const a of C) for (const b of C) pairs.push([a, b]);
  for (let i = 0; i < 60; i++) pairs.push([randomValue(random, k), randomValue(random, k)]);
  for (let i = 0; i < 30; i++)
    pairs.push([E[Math.floor(random() * E.length)]!, E[Math.floor(random() * E.length)]!]);
  // Small operands (bytes, indices): the common case.
  for (let i = 0; i < 40; i++)
    pairs.push([
      refValue(BigInt(Math.floor(random() * 300) - 20), k),
      refValue(BigInt(Math.floor(random() * 300) - 20), k),
    ]);
  for (const [a, b] of pairs) {
    for (const op of [...ARITH, ...CMP])
      c.check(binExpr(op, k, a, b), expected(refBinop(op, k, a, b), k));
  }
  // Division by powers of two (shift and mask fast paths) and small divisors.
  const w = WIDTH[k];
  for (let j = 1; j < w; j += 1 + Math.floor(random() * 3)) {
    for (const d of [1n << BigInt(j), -(1n << BigInt(j))]) {
      const b = refValue(d, k);
      for (const a of [randomValue(random, k), randomValue(random, k), E[0]!, E[E.length - 1]!]) {
        for (const op of ["/", "%", "*"] as BinOpKind[])
          c.check(binExpr(op, k, a, b), expected(refBinop(op, k, a, b), k));
      }
    }
  }
  // Unary ops and helpers over every edge value plus random ones.
  const un = [...E];
  for (let i = 0; i < 30; i++) un.push(randomValue(random, k));
  for (const a of un) {
    const A = lit(intToType(a, k));
    c.check(`I.Neg<${tag}, ${A}>`, expected(refUnop("-", k, a), k));
    c.check(`I.Not<${tag}, ${A}>`, expected(refUnop("^", k, a), k));
    c.check(`I.ToDec<${tag}, ${A}>`, lit(String(a)));
    c.check(`I.ToIndex<${tag}, ${A}>`, lit(String(a)));
    c.check(`I.IsZero<${A}>`, String(a === 0));
    c.check(`I.IsNeg<${tag}, ${A}>`, String(a < 0));
    c.check(`I.Sign<${tag}, ${A}>`, lit(a === 0 ? "0" : a < 0 ? "-" : "+"));
  }
  // Shifts: every count 0..w+1 and around 64, with counts of every kind.
  const shiftVals = [1, -1, 0x5a, E[0]!, E[E.length - 1]!, randomValue(random, k)].map((x) =>
    typeof x === "number" ? refValue(BigInt(x), k) : x,
  );
  const counts: bigint[] = [];
  for (let n = 0; n <= w + 1; n++) counts.push(BigInt(n));
  counts.push(63n, 64n, 65n, 127n, 128n, 200n, 255n, 1n << 40n, -1n, -64n, -128n);
  for (const a of shiftVals)
    for (const n of counts) {
      const ck = KINDS[Math.floor(random() * KINDS.length)]!;
      const cv = refValue(n, ck);
      for (const op of ["<<", ">>"] as BinOpKind[])
        c.check(binExpr(op, k, a, cv, ck), expected(refBinop(op, k, a, cv), k));
    }
  return c;
}

function convTests(seed: number): Cases {
  const random = rng(seed);
  const c = new Cases();
  for (const from of KINDS) {
    const vals = [...edges(from)];
    for (let i = 0; i < 10; i++) vals.push(randomValue(random, from));
    for (const to of KINDS)
      for (const a of vals)
        c.check(
          `I.Conv<${lit(intTag(from))}, ${lit(intTag(to))}, ${lit(intToType(a, from))}>`,
          expected(refConv(from, to, a), to),
        );
  }
  return c;
}

/** Every generated test file: path relative to the repo and its source. */
export function testFiles(): [string, string][] {
  const out: [string, string][] = KINDS.map((k, i) => [
    `tests/types/int-${intTag(k)}.gen.ts`,
    kindTests(k, 20261115 + i).source(),
  ]);
  out.push(["tests/types/int-conv.gen.ts", convTests(20261199).source()]);
  return out;
}

if (import.meta.main) {
  let n = 0;
  for (const [path, src] of testFiles()) {
    writeFileSync(resolve(ROOT, path), src);
    n += src.split("\n").filter((l) => l.startsWith("export type T")).length;
  }
  console.log(`${n} assertions`);
}
