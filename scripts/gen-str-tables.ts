// The source of src/types/str-tables.gen.ts: byte tables, UTF-8 tables and
// the generated block builder of the string index (src/types/str.ts, "Chars",
// adapted from lua-in-types' scripts/aot-str-tables.ts).
//
// Run by scripts/gen-strmap.ts (`vp run gen:strmap`).
import { strToType as tsLit } from "../src/types/codec-str.ts";
import { encodeInt64 } from "../src/types/codec-int.ts";

const encInt = (v: bigint | number) => encodeInt64(BigInt.asIntN(64, BigInt(v)));

const HEX = "0123456789abcdef".split("");
const N256 = Array.from({ length: 256 }, (_, i) => i);
const chr = (c: number) => String.fromCharCode(c);
/** LSB-first two nibbles of a byte. */
const nib2 = (c: number) => HEX[c & 15]! + HEX[c >> 4]!;
const q = (s: string) => JSON.stringify(s);

function table(name: string, doc: string, entries: [string, string][], sig: boolean): string {
  const lines = entries.map(([k, v]) => `  ${tsLit(k)}: ${v};`);
  if (sig) lines.unshift("  [key: string]: string;");
  return `/** ${doc} */\nexport type ${name} = {\n${lines.join("\n")}\n};\n`;
}

/** The 256-char block of the string index (see `Chars` in str.ts). */
function blockSource(): string {
  const v = (i: number) => `_${i}`;
  const infers = N256.map((i) => `\${infer ${v(i)}}`).join("");
  const sub = (h: number) =>
    `{ ${HEX.map((lo, l) => `${lo}: ${v(h * 16 + l)}`).join("; ")}; g: ${v(h * 16)} }`;
  const c = `{ ${HEX.map((hi, h) => `${hi}: ${sub(h)}`).join("; ")}; g: ${sub(0)} }`;
  const text = (n: number) =>
    "`" +
    N256.slice(0, n)
      .map((i) => `\${${v(i)}}`)
      .join("") +
    "`";
  const p = `{ ${HEX.map((hi, h) => `${hi}: ${text(h * 16)}`).join("; ")}; g: "" }`;
  return `/**
 * One full block of the string index: the next 256 chars of X as
 * \`[block, rest, last]\` (last is "ff" when nothing follows, else false), or
 * 0 when X is shorter. A block holds its chars (\`c[hi][lo]\`, nibbles of the
 * offset in the block), its text \`t\`, the prefixes \`p[hi]\` of 16 hi chars and
 * \`x\`, the rest of the string from the block on. Every node also answers "g"
 * like "0" (lookups pad positions with "g").
 */
export type Blk256<X extends string> = X extends \`${infers}\${infer R}\`
  ? [{ c: ${c}; t: ${text(256)}; p: ${p}; x: X }, R, R extends "" ? "ff" : false]
  : 0;

/** X without its first 256 chars, or 0 when it is shorter. */
export type Skip256<X extends string> = X extends \`${infers}\${infer R}\` ? R : 0;
`;
}

/** `PrefixAt<B, hi, lo>`: the first 16 hi + lo chars of block B. */
function prefixSource(): string {
  const cases = HEX.map((lo, l) => {
    const chars = Array.from({ length: l }, (_, i) => `\${B["c"][H]["${HEX[i]}"]}`).join("");
    return `L extends "${lo}" ? \`\${B["p"][H]}${chars}\``;
  });
  return `/** The first 16 H + L chars of block B (H, L nibbles; "g" counts as "0"). */
export type PrefixAt<B extends { c: any; p: any }, H extends string, L extends string> =
  ${cases.join("\n  : ")}
  : L extends "g" ? B["p"][H] : never;
`;
}

/** Go's utf8 rune encoding (src/ref/values.ts encodeRune). */
function utf8(r: number): string {
  if (r < 0x80) return chr(r);
  if (r < 0x800) return chr(0xc0 | (r >> 6)) + chr(0x80 | (r & 0x3f));
  if (r < 0x10000)
    return chr(0xe0 | (r >> 12)) + chr(0x80 | ((r >> 6) & 0x3f)) + chr(0x80 | (r & 0x3f));
  return (
    chr(0xf0 | (r >> 18)) +
    chr(0x80 | ((r >> 12) & 0x3f)) +
    chr(0x80 | ((r >> 6) & 0x3f)) +
    chr(0x80 | (r & 0x3f))
  );
}

export function strTablesSource(): string {
  const t: string[] = [
    `// Generated by scripts/gen-strmap.ts (\`vp run gen:strmap\`) from scripts/gen-str-tables.ts. Do not edit.\n`,
  ];
  const cont = N256.filter((c) => c >= 0x80 && c <= 0xbf);
  // ---- bytes
  t.push(
    table(
      "CODE",
      "A byte (one char) -> its value as a uint8 in the integer encoding (the 8-bit pattern sign-extended).",
      N256.map((c) => [chr(c), q(encInt(BigInt.asIntN(8, BigInt(c))))]),
      true,
    ),
    table(
      "CHR",
      "An 8-bit integer (uint8 or int8, encoded) -> its byte.",
      N256.map((c) => [encInt(BigInt.asIntN(8, BigInt(c))), tsLit(chr(c))]),
      true,
    ),
    table(
      "HEX2",
      "A byte -> its two hex digits, most significant first (byte order for comparisons).",
      N256.map((c) => [chr(c), q(HEX[c >> 4]! + HEX[c & 15]!)]),
      true,
    ),
    table(
      "CMPN",
      'Two nibbles a, b -> "<", "=" or ">".',
      N256.map((c) => {
        const a = c >> 4;
        const b = c & 15;
        return [HEX[a]! + HEX[b]!, q(a < b ? "<" : a > b ? ">" : "=")];
      }),
      true,
    ),
    table(
      "NEXT2",
      'An offset in a block (two nibbles, least significant first) -> the next one; "ff" -> "t" (the block\'s end).',
      N256.map((c) => [nib2(c), q(c === 255 ? "t" : nib2(c + 1))]),
      true,
    ),
  );
  // ---- UTF-8 decoding
  t.push(
    table(
      "CLS",
      'A byte -> its UTF-8 role: "1" ASCII, "2"/"3"/"4" a lead byte of that sequence length, "x" invalid as a first byte.',
      N256.map((c) => [
        chr(c),
        q(
          c < 0x80 ? "1" : c < 0xc2 ? "x" : c < 0xe0 ? "2" : c < 0xf0 ? "3" : c <= 0xf4 ? "4" : "x",
        ),
      ]),
      true,
    ),
  );
  const dec2: [string, string][] = [];
  const d3a: [string, string][] = [];
  const d4a: [string, string][] = [];
  for (let c0 = 0xc2; c0 <= 0xf4; c0++) {
    for (const c1 of cont) {
      if (c0 < 0xe0) {
        dec2.push([chr(c0) + chr(c1), q(encInt(((c0 & 0x1f) << 6) | (c1 & 0x3f)))]);
      } else if (c0 < 0xf0) {
        if (c0 === 0xe0 && c1 < 0xa0) continue;
        if (c0 === 0xed && c1 > 0x9f) continue;
        const r = ((c0 & 0x0f) << 12) | ((c1 & 0x3f) << 6);
        d3a.push([chr(c0) + chr(c1), q(String(c1 & 3) + encInt(r).slice(2))]);
      } else {
        if (c0 === 0xf0 && c1 < 0x90) continue;
        if (c0 === 0xf4 && c1 > 0x8f) continue;
        const r = ((c0 & 0x07) << 18) | ((c1 & 0x3f) << 12);
        d4a.push([chr(c0) + chr(c1), q(encInt(r).slice(3))]);
      }
    }
  }
  t.push(
    table("DEC2", "A valid 2-byte sequence -> its rune.", dec2, false),
    table(
      "D3A",
      "The first two bytes of a valid 3-byte sequence -> k (bits 1..0 of the second byte) and the rune's nibbles from the third up.",
      d3a,
      false,
    ),
    table(
      "D3B",
      "k and a continuation byte -> the rune's two low nibbles (3-byte sequences).",
      [0, 1, 2, 3].flatMap((k) =>
        cont.map((c2): [string, string] => [
          String(k) + chr(c2),
          q(HEX[c2 & 15]! + HEX[((c2 >> 4) & 3) | (k << 2)]!),
        ]),
      ),
      false,
    ),
    table(
      "D4A",
      "The first two bytes of a valid 4-byte sequence -> the rune's nibbles from the fourth up.",
      d4a,
      false,
    ),
    table(
      "D4B",
      "Two continuation bytes -> the rune's three low nibbles (4-byte sequences).",
      cont.flatMap((c2) =>
        cont.map((c3): [string, string] => [
          chr(c2) + chr(c3),
          q(HEX[c3 & 15]! + HEX[((c3 >> 4) & 3) | ((c2 & 3) << 2)]! + HEX[(c2 >> 2) & 15]!),
        ]),
      ),
      false,
    ),
  );
  // ---- UTF-8 encoding
  const enc12: [string, string][] = [];
  for (let r = 0; r < 0x800; r++) enc12.push([encInt(r), tsLit(utf8(r))]);
  const e3a: [string, string][] = [];
  for (let n3 = 0; n3 < 16; n3++)
    for (let n2 = 0; n2 < 16; n2++) {
      if (n3 === 0 && n2 < 8) continue; // < 0x800: not this form
      if (n3 === 0xd && n2 >= 8) continue; // surrogates
      e3a.push([HEX[n3]! + HEX[n2]! + (n3 >= 8 ? "0" : ""), tsLit(chr(0xe0 | n3))]);
    }
  const e4h: [string, string][] = [];
  for (let n5 = 0; n5 < 2; n5++)
    for (let n4 = 0; n4 < 16; n4++) {
      if (n5 === 0 && n4 === 0) continue;
      if (n5 === 1 && n4 !== 0) continue;
      const rest = n5 === 1 ? "01" : HEX[n4]! + (n4 >= 8 ? "0" : "");
      for (let n3 = 0; n3 < 16; n3++)
        e4h.push([
          rest + HEX[n3]!,
          tsLit(chr(0xf0 | (n5 << 2) | (n4 >> 2)) + chr(0x80 | ((n4 & 3) << 4) | n3)),
        ]);
    }
  const e4l: [string, string][] = [];
  for (let n2 = 0; n2 < 16; n2++)
    for (let n1 = 0; n1 < 16; n1++)
      for (let n0 = 0; n0 < 16; n0++)
        e4l.push([
          HEX[n2]! + HEX[n1]! + HEX[n0]!,
          tsLit(chr(0x80 | (n2 << 2) | (n1 >> 2)) + chr(0x80 | ((n1 & 3) << 4) | n0)),
        ]);
  t.push(
    table("ENC12", "A rune 0..0x7ff -> its UTF-8 bytes.", enc12, false),
    table(
      "E3A",
      'Nibbles 3, 2 of a rune 0x800..0xffff and its sign nibble ("" or "0") -> the first byte; surrogates are absent.',
      e3a,
      false,
    ),
    table(
      "E4H",
      "A rune 0x10000..0x10ffff's nibbles from the fifth up, then nibble 3 -> its first two bytes.",
      e4h,
      false,
    ),
    table("E4L", "Nibbles 2, 1, 0 of a rune -> its last two UTF-8 bytes.", e4l, true),
  );
  // ---- counters and decimal
  t.push(
    table(
      "FUEL",
      "Loop fuel: n -> n - 1 (decimal, 1..1000).",
      Array.from({ length: 1000 }, (_, i): [string, string] => [String(i + 1), q(String(i))]),
      true,
    ),
  );
  t.push(
    `/** Tuple length 0..16 -> nibble (16 -> "g"). */\nexport type HEX = [${[...HEX, "g"].map((h) => `"${h}"`).join(", ")}];\n`,
  );
  t.push(blockSource(), prefixSource());
  return t.join("\n");
}
