/**
 * Random op sequences on a map state, checked after every step against
 * src/ref/gomap.ts: lookups, len, full iteration, and iterations that
 * insert and delete between steps.
 */
function mapTests(): string {
  const out: string[] = [
    "// Generated by scripts/gen-strmap.ts (`vp run gen:strmap`). Do not edit.",
    "// Random map op sequences; expected values from src/ref/gomap.ts.",
    'import type * as M from "../../src/types/map.ts";',
    'import type * as H from "../../src/types/heap.ts";',
    "",
    "type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;",
    "type Assert<T extends true> = T;",
    "/** Every [key, value] in iteration order. */",
    'type All<MS, It extends string = "0", O extends unknown[] = []> =',
    "  M.MsNext<MS, It, 0, 0> extends [infer ok, infer k, infer v, infer it extends string]",
    "    ? ok extends true",
    "      ? All<MS, it, [...O, [k, v]]>",
    "      : O",
    "    : never;",
    "",
  ];
  let nt = 0;
  const check = (actual: string, expected: string) =>
    out.push(`export type T${nt++} = Assert<Equal<${actual}, ${expected}>>;`);

  /** Pairs of distinct strings with the same hash (bucket chains). */
  const collide: string[] = [];
  {
    const seen = new Map<string, string>();
    for (let i = 0; collide.length < 12; i++) {
      const k = "c" + i.toString(36);
      const h = strHash(k);
      const o = seen.get(h);
      if (o !== undefined && !collide.includes(o)) collide.push(o, k);
      else seen.set(h, k);
    }
  }

  type Cfg = { name: string; mode: "s" | "i"; ops: number; keys: () => string; iterEvery: number };
  const strPool = [
    "",
    "a",
    "b",
    "length",
    "push",
    "__proto__",
    "\xff\x00",
    "x".repeat(40),
    ...collide,
  ];
  for (let i = 0; i < 20; i++) strPool.push(bytes(1 + ri(12), i % 3 ? 26 : 256));
  const intPool: bigint[] = [0n, 1n, -1n, 7n, 8n, 15n, 16n, 255n, -(2n ** 63n), 2n ** 63n - 1n];
  for (let i = 0; i < 12; i++) intPool.push(BigInt(0x10000 * ri(5) + 5)); // same low 4 nibbles
  for (let i = 0; i < 10; i++) intPool.push(BigInt(ri(100000)) - 50000n);
  const cfgs: Cfg[] = [];
  for (let i = 0; i < 24; i++)
    cfgs.push({
      name: `F${i}`,
      mode: i % 3 === 2 ? "i" : "s",
      ops: 40 + ri(40),
      keys:
        i % 3 === 2
          ? () => String(intPool[ri(intPool.length)])
          : () => strPool[ri(strPool.length)]!,
      iterEvery: 15,
    });
  // A large map: grows the order trie to depth 3 and spreads the index.
  cfgs.push({ name: "Big", mode: "s", ops: 1200, keys: () => "k" + ri(700), iterEvery: 400 });

  for (const c of cfgs) {
    const isInt = c.mode === "i";
    const keyT = (k: string) => (isInt ? int(BigInt(k)) : lit(k));
    const ref = new GoMap(0, (k) => k);
    let st = 0;
    const S = (n: number) => `${c.name}_${n}`;
    out.push(`export type ${S(0)} = M.MsEmpty<"${c.mode}">;`);
    const iterAll = () => {
      const it = new MapIter(ref);
      const es: string[] = [];
      for (let e = it.next(); e; e = it.next()) es.push(`[${keyT(e.k)}, ${q(e.v)}]`);
      check(`All<${S(st)}>`, `[${es.join(", ")}]`);
    };
    for (let i = 0; i < c.ops; i++) {
      const k = c.keys();
      const r = rand();
      if (r < 0.6) {
        const v = "v" + i;
        ref.set(k, v);
        out.push(`export type ${S(st + 1)} = M.MsSet<${S(st)}, ${keyT(k)}, ${keyT(k)}, ${q(v)}>;`);
        st++;
      } else if (r < 0.85) {
        ref.delete(k);
        out.push(`export type ${S(st + 1)} = M.MsDel<${S(st)}, ${keyT(k)}>;`);
        st++;
      } else if (r < 0.86 && c.ops < 200) {
        ref.clear();
        out.push(`export type ${S(st + 1)} = M.MsClear<${S(st)}>;`);
        st++;
      }
      if (c.ops < 200 || i % 50 === 0) {
        const e = ref.get(k);
        check(`M.MsLookupOk<${S(st)}, ${keyT(k)}, "z">`, e ? `[${q(e.v)}, true]` : `["z", false]`);
        check(`M.MsLen<${S(st)}>`, int(ref.size));
      }
      if (i % c.iterEvery === c.iterEvery - 1) iterAll();
    }
    iterAll();
    // The codec prints the same state.
    check(
      S(st),
      mapStateToType(
        ref,
        {
          mode: c.mode,
          canon: (k) => (isInt ? encInt(BigInt(k as string)) : (k as string)),
          keyText: (k) => keyT(k as string),
          keyFrom: () => null,
        },
        { valText: (v) => q(v as string), valFrom: () => null },
        { mk6: "M.MapMk6", mk5: "M.MapMk5", mk16: "M.MapMk16" },
      ),
    );
    // A range loop that mutates the map between steps (Go allows both).
    if (c.ops < 200) {
      const it = new MapIter(ref);
      let itT = "0";
      let n = 0;
      for (let step = 0; step < 30; step++) {
        const e = it.next();
        const name = `${c.name}_N${n++}`;
        out.push(`export type ${name} = M.MsNext<${S(st)}, ${q(itT)}, 0, 0>;`);
        if (!e) {
          check(name, `[false, 0, 0, ${q(itT)}]`);
          break;
        }
        itT = encInt(e.seq + 1);
        check(name, `[true, ${keyT(e.k)}, ${q(e.v)}, ${q(itT)}]`);
        const k = c.keys();
        const r = rand();
        if (r < 0.4) {
          ref.set(k, "w" + step);
          out.push(
            `export type ${S(st + 1)} = M.MsSet<${S(st)}, ${keyT(k)}, ${keyT(k)}, "w${step}">;`,
          );
          st++;
        } else if (r < 0.8) {
          // Sometimes delete the entry just visited, or one not reached yet.
          const dk = r < 0.55 ? e.k : k;
          ref.delete(dk);
          out.push(`export type ${S(st + 1)} = M.MsDel<${S(st)}, ${keyT(dk)}>;`);
          st++;
        }
      }
    }
  }

  // ---- maps on the heap
  out.push(
    "export type G0 = H.HeapEmpty;",
    "export type GM = M.MakeMapV<G0>;",
    'export type G1 = M.MakeMap<G0, "s">;',
    'export type G2 = M.MapUpdate<G1, GM, "a", "a", "1">;',
    'export type G3 = M.MapUpdate<G2, GM, "b", "b", "2">;',
    'export type G4 = M.MapUpdate<G3, GM, "c", "c", "3">;',
    'export type G5 = M.MapDelete<G4, GM, "a">;',
    "export type GC = M.MakeMapV<G5>;",
    "export type G6 = M.MapClone<G5, GM>;",
    'export type G7 = M.MapUpdate<G6, GC, "d", "d", "4">;',
    "export type G8 = M.MapClear<G7, GM>;",
  );
  check("GM", q("00001"));
  check('M.MapLookupOk<G4, GM, "a", "z">', '["1", true]');
  check('M.MapLookupOk<G5, GM, "a", "z">', '["z", false]');
  check('M.MapLookup<G5, GM, "b", "z">', '"2"');
  check('M.MapLookup<G5, null, "b", "z">', '"z"');
  check('M.MapLookupOk<G5, null, "b", "z">', '["z", false]');
  check("M.MapLen<G5, GM>", '"2"');
  check("M.MapLen<G5, null>", '"0"');
  check("M.MapUpdateCk<GM>", "true");
  check("M.MapUpdateCk<null>", '["panic", "assignment to entry in nil map"]');
  check('M.MapDelete<G5, null, "a">', "G5");
  check("M.MapClear<G5, null>", "G5");
  check('M.MapNext<G5, GM, "0", 0, 0>', '[true, "b", "2", "2"]');
  check('M.MapNext<G5, null, "0", 0, 0>', '[false, 0, 0, "0"]');
  check("GC", q("00002"));
  check('M.MapNext<G7, GC, "0", 0, 0>', '[true, "b", "2", "1"]');
  check("All<H.GetObj<G7, GC>>", '[["b", "2"], ["c", "3"], ["d", "4"]]');
  check("All<H.GetObj<G7, GM>>", '[["b", "2"], ["c", "3"]]');
  check("H.GetObj<G6, GC>", 'M.MsSet<M.MsSet<M.MsEmpty<"s">, "b", "b", "2">, "c", "c", "3">');
  check("M.MapLen<G8, GM>", '"0"');
  check("M.MapLen<G8, GC>", '"3"');
  // maps.clone of a larger map (several fuel chunks).
  {
    const ref = new GoMap(0, (k) => k);
    let st = 'M.MsEmpty<"s">';
    out.push(`export type CL0 = ${st};`);
    for (let i = 0; i < 700; i++) {
      const k = "q" + ri(500);
      if (rand() < 0.8) {
        ref.set(k, "v" + i);
        out.push(`export type CL${i + 1} = M.MsSet<CL${i}, ${q(k)}, ${q(k)}, "v${i}">;`);
      } else {
        ref.delete(k);
        out.push(`export type CL${i + 1} = M.MsDel<CL${i}, ${q(k)}>;`);
      }
    }
    void st;
    const es: string[] = [];
    const it = new MapIter(ref);
    for (let e = it.next(); e; e = it.next()) es.push(`[${q(e.k)}, ${q(e.v)}]`);
    out.push("export type CLR = M.MsRebuild<CL700>;");
    check("All<CLR>", `[${es.join(", ")}]`);
    check("M.MsLen<CLR>", int(ref.size));
    check("CLR[1]", int(ref.size));
  }
  out.push("");
  return out.join("\n");
}

